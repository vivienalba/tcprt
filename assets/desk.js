export function initDesk({doc,win,anime,effects,getMotion=()=>true,onReset=()=>{}}={}){
  const desk=doc.querySelector('.object-desk');
  const objects=Array.from(desk.querySelectorAll('.desk-object'));
  const reset=doc.querySelector('#reset-desk'),toolbar=doc.querySelector('.desk-toolbar>span');
  const fine=win.matchMedia('(pointer: fine)');
  const draggables=[],listeners=[];
  const listen=(target,type,fn,options)=>{target.addEventListener(type,fn,options);listeners.push(()=>target.removeEventListener(type,fn,options));};
  function updateHint(){
    toolbar.innerHTML='<span class="tiny-cross" aria-hidden="true">✳</span> '+(fine.matches?'DRAG A THING. CLICK TO EXPLORE.':'DRAG OR TAP A THING.');
  }
  objects.forEach(element=>{
    let start=null,dragged=false,suppressUntil=0;
    listen(element,'pointerdown',event=>{
      if(event.isPrimary===false||(event.pointerType==='mouse'&&event.button!==0))return;
      start={x:event.clientX,y:event.clientY,touch:event.pointerType==='touch',id:event.pointerId};dragged=false;suppressUntil=0;
    },{passive:true});
    listen(win,'pointermove',event=>{
      if(!start||event.pointerId!==start.id)return;
      if(Math.hypot(event.clientX-start.x,event.clientY-start.y)>=(start.touch?7:4))dragged=true;
    },{passive:true});
    const finishPointer=event=>{if(!start||event.pointerId!==start.id)return;if(dragged)suppressUntil=win.performance.now()+700;start=null;};
    listen(win,'pointerup',finishPointer,{passive:true});
    listen(win,'pointercancel',event=>{if(!start||event.pointerId!==start.id)return;start=null;dragged=false;suppressUntil=0;element.dataset.dragging='false';element.style.zIndex='2';effects.holdObject(element,false);},{passive:true});
    // Suppress only the click generated by this drag. Keyboard activation and
    // a fresh pointer-down/tap still open the project immediately.
    listen(element,'click',event=>{
      if(event.detail!==0&&(dragged||win.performance.now()<suppressUntil)){
        event.preventDefault();event.stopImmediatePropagation();dragged=false;suppressUntil=0;
      }
    },true);
    const draggable=anime.createDraggable(element,{
      container:desk,containerPadding:0,containerFriction:1,releaseContainerFriction:1,
      dragThreshold:{mouse:4,touch:7},scrollThreshold:0,velocityMultiplier:0,releaseEase:'out(3)',
      onGrab:()=>{effects.cancel([draggable],'reset');element.style.zIndex='8';effects.holdObject(element,true);},
      onDrag:()=>{dragged=true;element.dataset.dragging='true';},
      onRelease:()=>{
        if(dragged)suppressUntil=win.performance.now()+700;
        element.dataset.dragging='false';element.style.zIndex='2';effects.holdObject(element,false);
      },
      onSettle:()=>{element.style.zIndex='2';}
    });
    draggables.push(draggable);
  });
  reset.disabled=false;reset.style.opacity='1';updateHint();
  listen(fine,'change',updateHint);
  listen(reset,'click',()=>{
    draggables.forEach((draggable,index)=>{
      const element=objects[index];draggable.stop();element.dataset.dragging='false';element.style.zIndex='2';effects.holdObject(element,false);
      // Animate the public x/y properties so the Draggable's own position
      // stays in sync. Grabbing halfway through a reset preserves that position.
      if(getMotion())effects.animate([draggable],{x:0,y:0,duration:320,delay:index*18,onComplete:()=>draggable.reset()},'reset');else draggable.reset();
    });
    onReset();
  });
  return {destroy(){listeners.forEach(remove=>remove());draggables.forEach(draggable=>draggable.revert());}};
}
